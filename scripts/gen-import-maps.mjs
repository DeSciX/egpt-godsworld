/**
 * gen-import-maps.mjs — the ONE writer of the site's import maps: the block between IMPORT_MAP_MARKERS in each page
 * that imports the vendored @descix/frqtl-web by specifier (PAGES: the front page, index.html, for its host-view declaration;
 * the lab, app.html; and the scene frame, scene.html),
 * and of the ONE site module that reaches the package by path, PROJECT_DOOR.
 *
 * The map is the package's own, never re-typed here: `pageImportMapFor(SITE_ROOT)` from the vendored `./project` — every
 * sketch row (FRQTL_WEB_SPECIFIERS, the table a scene's imports must name) plus every host row (FRQTL_WEB_HOST_SPECIFIERS:
 * ./boot, ./registry, ./project). The map has no dist-manifest row: a page reads the manifest from the root it holds
 * (`new URL('dist-manifest.json', root)`; maxi-lab.js). The site's pages sit at the site root, so the relative root
 * `./vendor/…` resolves under ANY path prefix (`descix serve`, PROD).
 *
 * PROJECT_DOOR (site/app-assets/frqtl-web-project.js) re-exports the map's ./project row as a relative import, so a site
 * module that node imports too (maxi-hands.js, maxi-record-folder.js) reaches the package's Record format: node has no
 * import map, and a node importer cannot register a resolve hook before its static graph links. In the page the door's
 * import resolves to the SAME URL as the map's row, so it is the same module instance as `@descix/frqtl-web/project`.
 * The door also imports the map's ./parts row (PARTS_SPECIFIER) for its registrations: ./project's applyRows reads a
 * part kind's descriptor (ObjectSchema.derivedReads), which a kind has only in a realm that imported its part module, and
 * the lab's frame and node import no part otherwise.
 *
 *   node scripts/gen-import-maps.mjs             # print the block
 *   node scripts/gen-import-maps.mjs --write     # rewrite ONLY what sits between the markers of each page, and the door
 *   node scripts/gen-import-maps.mjs --check     # exit 1 when any page's block, or the door, is stale
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REPO, PINNED, SITE_DIST, distUrl, exportFile } from './frqtl-web-pin.mjs';

const PROJECT = await import(distUrl(exportFile('./project')));
for (const name of ['pageImportMapFor', 'FRQTL_WEB_SPECIFIERS', 'FRQTL_WEB_HOST_SPECIFIERS']) {
    if (PROJECT[name] === undefined) {
        throw new Error('[gen-import-maps] ' + PINNED.name + '@' + PINNED.version + ' ./project exports no ' + name +
            ' — the site\'s import map is the package\'s own pageImportMapFor(root); re-vendor a version that has it. (FAIL-LOUD.)');
    }
}
const { pageImportMapFor, FRQTL_WEB_SPECIFIERS, FRQTL_WEB_HOST_SPECIFIERS } = PROJECT;

export const IMPORT_MAP_MARKERS = Object.freeze({
    begin: '<!-- IMPORT-MAP:BEGIN generated by scripts/gen-import-maps.mjs from site/vendor/frqtl-web/PINNED.json -->',
    end: '<!-- IMPORT-MAP:END -->'
});

/** The pages that import the package by specifier (site-relative): index.html through maxi-host-view.js only. */
export const PAGES = Object.freeze(['index.html', 'app.html', 'scene.html']);

/** The vendored dist root as seen from a page at the site root: an import-map value must be a URL or start with /, ./ or ../. */
export const SITE_ROOT = './' + SITE_DIST + '/';

/** The page's one import map: the package's pageImportMapFor at the vendored root. */
export function siteImportMap() {
    return pageImportMapFor(SITE_ROOT);
}

export function renderBlock() {
    const json = JSON.stringify(siteImportMap(), null, 2);
    return IMPORT_MAP_MARKERS.begin + '\n<script type="importmap">\n' + json + '\n</script>\n' + IMPORT_MAP_MARKERS.end;
}

/** One page with its block rendered: {next, stale}. THROWS when the page lacks exactly one marker pair. */
export function renderPage(text, where) {
    const m = IMPORT_MAP_MARKERS;
    const b = text.indexOf(m.begin);
    const e = text.indexOf(m.end);
    if (b === -1 || e === -1 || e < b || text.indexOf(m.begin, b + 1) !== -1 || text.indexOf(m.end, e + 1) !== -1) {
        throw new Error('[gen-import-maps] ' + where + ' does not carry exactly one import-map block — put these two lines, once, in its <head> ' +
            'before any module script:\n' + m.begin + '\n' + m.end);
    }
    const current = text.slice(b, e + m.end.length);
    const block = renderBlock();
    return { next: text.slice(0, b) + block + text.slice(e + m.end.length), stale: current !== block };
}

export const SPECIFIER_COUNT = FRQTL_WEB_SPECIFIERS.length;
const HOST_COUNT = FRQTL_WEB_HOST_SPECIFIERS.length;
{
    const rows = Object.keys(siteImportMap().imports).length;
    if (rows !== SPECIFIER_COUNT + HOST_COUNT) {
        throw new Error('[gen-import-maps] pageImportMapFor(root) has ' + rows + ' rows, not the ' + SPECIFIER_COUNT + ' sketch rows (FRQTL_WEB_SPECIFIERS) + ' +
            HOST_COUNT + ' host rows (FRQTL_WEB_HOST_SPECIFIERS) the package declares. (FAIL-LOUD.)');
    }
}

/** The package's ./project specifier: the host row the door re-exports (FRQTL_WEB_HOST_SPECIFIERS). */
export const PROJECT_SPECIFIER = '@descix/frqtl-web/project';
/** The one site module that reaches the vendored ./project by path (site-relative), rendered here. */
export const PROJECT_DOOR = 'app-assets/frqtl-web-project.js';

/** The package's ./parts specifier: the sketch row the door imports for its kind registrations (FRQTL_WEB_SPECIFIERS). */
export const PARTS_SPECIFIER = '@descix/frqtl-web/parts';

/** A map row's value as an import relative to the door. THROWS when the map has no such row. */
function fromDoorOf(specifier) {
    const mapped = siteImportMap().imports[specifier];
    if (typeof mapped !== 'string' || !mapped.startsWith(SITE_ROOT)) {
        throw new Error('[gen-import-maps] the map resolves ' + specifier + ' to ' + JSON.stringify(mapped) + ', not a file under ' + SITE_ROOT + '. (FAIL-LOUD.)');
    }
    return path.posix.relative(path.posix.dirname(PROJECT_DOOR), mapped.replace(/^\.\//, ''));
}

/**
 * The door's text: an import of the map's ./parts row (the part kinds registered where the door loads: applyRows reads their
 * descriptors) and one re-export of its ./project row, both relative to the door. THROWS when the host table has no ./project
 * row or the map no ./parts row.
 */
export function renderProjectDoor() {
    const row = FRQTL_WEB_HOST_SPECIFIERS.find(function (r) { return r.specifier === PROJECT_SPECIFIER; });
    if (!row) { throw new Error('[gen-import-maps] ' + PINNED.name + '@' + PINNED.version + ' FRQTL_WEB_HOST_SPECIFIERS has no ' + PROJECT_SPECIFIER + ' row. (FAIL-LOUD.)'); }
    const mapped = siteImportMap().imports[PROJECT_SPECIFIER];
    if (mapped !== SITE_ROOT + row.libPath) { throw new Error('[gen-import-maps] the map resolves ' + PROJECT_SPECIFIER + ' to ' + mapped + ', not ' + SITE_ROOT + row.libPath + '. (FAIL-LOUD.)'); }
    return '/* Copyright 2023-2026 by Essam Abadir */\n\n' +
        '// GENERATED by scripts/gen-import-maps.mjs from site/vendor/frqtl-web/PINNED.json — never edit by hand.\n' +
        '// ' + PINNED.name + '@' + PINNED.version + ' ' + PROJECT_SPECIFIER + ' for the site modules node imports too: the same file the page\'s\n' +
        '// import map names for ' + PROJECT_SPECIFIER + ', so in the page it is the same module instance. ' + PARTS_SPECIFIER + ' is imported\n' +
        '// for its registrations: applyRows reads a part kind\'s descriptor, which a kind has only in a realm that imported its part.\n' +
        'import \'' + fromDoorOf(PARTS_SPECIFIER) + '\';\n' +
        'export * from \'' + fromDoorOf(PROJECT_SPECIFIER) + '\';\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const mode = process.argv[2];
    if (process.argv.length > 3 || (mode !== undefined && mode !== '--write' && mode !== '--check')) {
        console.error('usage: gen-import-maps.mjs [--write | --check]');
        process.exit(2);
    }
    if (mode === undefined) { process.stdout.write(renderBlock() + '\n'); process.exit(0); }
    const stale = [];
    const doorFile = path.join(REPO, 'site', PROJECT_DOOR);
    const door = renderProjectDoor();
    if (!fs.existsSync(doorFile) || fs.readFileSync(doorFile, 'utf8') !== door) {
        stale.push('site/' + PROJECT_DOOR);
        if (mode === '--write') { fs.writeFileSync(doorFile, door); }
    }
    for (const page of PAGES) {
        const file = path.join(REPO, 'site', page);
        const r = renderPage(fs.readFileSync(file, 'utf8'), 'site/' + page);
        if (r.stale) {
            stale.push('site/' + page);
            if (mode === '--write') { fs.writeFileSync(file, r.next); }
        }
    }
    if (mode === '--check' && stale.length) {
        console.error('[gen-import-maps] stale: ' + stale.join(', ') + ' — run node scripts/gen-import-maps.mjs --write');
        process.exit(1);
    }
    console.log('[gen-import-maps] ' + (mode === '--write' ? 'wrote ' + (stale.join(', ') || 'nothing (already current)') : 'current') +
        ' — ' + PINNED.name + '@' + PINNED.version + ', ' + SPECIFIER_COUNT + ' sketch rows + ' + HOST_COUNT + ' host rows (pageImportMapFor), and the ./project door');
}
