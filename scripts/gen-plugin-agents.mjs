/**
 * gen-plugin-agents.mjs — MiniMaxi's three local agents, generated from the two owners.
 *
 *   node scripts/gen-plugin-agents.mjs            # print the three files
 *   node scripts/gen-plugin-agents.mjs --write    # write plugin/agents/maxi-<role>.md and the skill's ROLES table
 *   node scripts/gen-plugin-agents.mjs --check    # exit 1 when any of them is stale or missing
 *
 * The runbook plugin/skills/minimaxi/SKILL.md carries the roles table between the ROLES markers; it is
 * rendered here from ROLES too, never typed by hand (a hand table drifted: verifier, 2026-10-14).
 *
 * Each agent is: frontmatter (name, description — from ROLES in site/app-assets/maxi-roles.js; tools — TOOL_NEEDS here),
 * how a local turn runs (the turn file / answer file hand-off minimaxi/loop.mjs --brain local makes),
 * then — for a role that runs under the persona on the platform (ROLES[id].persona) — the persona
 * assets/system_instructions.md VERBATIM, so the local and the platform loop differ only in who answers;
 * a role that runs without it (the Owl, on KB General) gets a line saying so instead. The world frame
 * (maxi-roles.js WORLD_FRAME) reaches the Designer and the Builder through the persona's generated WORLD FRAME
 * section (so through these files), and the Owl through its first turn; the skill's roles block shows it once. The role itself arrives
 * in the turn text (maxi-roles.js turn builders), exactly as on the platform. Nothing here is typed by
 * hand twice: scripts/test/roles.test.mjs fails when a file drifts from this output.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROLES, ROLE_ORDER, HANDOFF_TAGS, WORLD_FRAME, READING_LINE, DESIGNER_READINGS } from '../site/app-assets/maxi-roles.js';
import { ANSWER_SUFFIX } from './gen-memories-seen.mjs';   // the thread format's owner: the loop writes, the generator serves

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const AGENTS_DIR = 'plugin/agents';
export const PERSONA = 'assets/system_instructions.md';
export const agentName = (id) => 'maxi-' + id;
export const agentPath = (id) => AGENTS_DIR + '/' + agentName(id) + '.md';
export const SKILL = 'plugin/skills/minimaxi/SKILL.md';
export const ROLES_MARKERS = Object.freeze({
    begin: '<!-- ROLES:BEGIN generated by scripts/gen-plugin-agents.mjs from site/app-assets/maxi-roles.js -->',
    end: '<!-- ROLES:END -->'
});

const HANDOFF_BY_ROLE = {
    designer: 'ONE ```' + HANDOFF_TAGS.plan + '``` block for an outline, or ONE ```' + HANDOFF_TAGS.answer + '``` block for a question (the answer block, then the plan block, for both), its FIRST line `' + READING_LINE + ' …` reading the message',
    builder: 'ONE ```' + HANDOFF_TAGS.call + '<hand>``` block with its `PREDICTION:` line before it, or ONE ```' + HANDOFF_TAGS.done + '``` block',
    owl: 'ONE ```' + HANDOFF_TAGS.verdict + '``` block, its `seen` account of the footage first'
};

/**
 * The agent's tools, one owner: each tool is granted for a line its own HOW THIS AGENT RUNS text carries, and only for
 * that. A role's tools are the tools whose line appears in its rendered text, in this order; nothing is listed by hand.
 * The Owl's text names no body CLI and no kb/ tree to read, so it gets Read and Write only (its isolation stands).
 */
export const TOOL_NEEDS = Object.freeze([
    Object.freeze({ tool: 'Bash', why: 'runs the body CLI for reading hands', when: /you may run READING hands yourself with the body CLI/ }),
    Object.freeze({ tool: 'Read', why: 'reads its turn file (and opens the frames)', when: /Read the turn file/ }),
    Object.freeze({ tool: 'Write', why: 'writes its reply to the answer file', when: /Write your reply to the answer file/ }),
    Object.freeze({ tool: 'Grep', why: 'searches the kb/ tree it reads', when: /^You read: [^\n]*\bkb\/[A-Za-z]/m }),
    Object.freeze({ tool: 'Glob', why: 'lists the kb/ tree it reads', when: /^You read: [^\n]*\bkb\/[A-Za-z]/m })
]);

/** The tools a rendered HOW THIS AGENT RUNS text requires (TOOL_NEEDS order). */
export function toolsFor(howText) {
    const tools = TOOL_NEEDS.filter(function (n) { return n.when.test(howText); }).map(function (n) { return n.tool; });
    const missing = TOOL_NEEDS.filter(function (n) { return (n.tool === 'Read' || n.tool === 'Write') && tools.indexOf(n.tool) === -1; })
        .map(function (n) { return n.tool + ' (no line matching ' + n.when + ': the turn ' + n.why + ')'; });
    if (missing.length) {
        throw new Error('[gen-plugin-agents] a local turn reads its turn file and writes its answer file; this text lacks ' + missing.join(' and ') + ' — refusing to generate an agent that cannot take its turn.');
    }
    return tools;
}

function howLocal(r) {
    const lines = [
        '# HOW THIS AGENT RUNS (MiniMaxi, local brain)',
        '',
        'You are ' + r.name + (r.name !== r.title ? ' (' + r.title + ')' : '') + ' — the ' + r.metaphor + ' — run by the `minimaxi` skill. Your prompt names a',
        'TURN FILE `minimaxi/out/turns/<run>/<n>-' + r.id + '.md` and its ANSWER FILE `<n>-' + r.id + ANSWER_SUFFIX + '`. Read the turn file: it',
        'holds your turn text — exactly what the platform brain would be asked — and, when the turn carries footage,',
        'the paths of frame images sampled from the clip in order. Write your reply to the answer file, as the',
        'whole reply text, ending with ' + HANDOFF_BY_ROLE[r.id] + '. Nothing else ends your turn: the loop reads',
        'the answer file, and a malformed hand-off stops the loop loudly.',
        '',
        'You read: ' + r.localReads + '.'
    ];
    if (r.id === 'owl' || r.id === 'builder') {
        lines.push('', 'FOOTAGE: the clip is given to you as its sampled frames. Open EVERY frame path with the Read tool, in',
            'order, before you write a word about it; what you say you saw comes from those images only. If a frame',
            'will not open, say so in your reply — never describe a frame you did not open.');
    }
    if (r.id === 'builder') {
        lines.push('', 'Your acting hands go in your answer as the json:call block (the loop runs it through the body and',
            'films); you may run READING hands yourself with the body CLI named in the turn file (inventory,',
            'sceneSource) to look before you act.');
    }
    if (r.id === 'owl') {
        lines.push('', 'You are the distinct verifier: do not open the memories (kb/), the sketches, the plan or any other turn',
            'file. The outline, the prediction and the frames in your turn file are all you judge from.');
    }
    return lines.join('\n');
}

/** The full text of one agent file. */
export function renderAgent(id, persona) {
    const r = ROLES[id];
    if (!r) { throw new Error('[gen-plugin-agents] no role "' + id + '".'); }
    if (typeof persona !== 'string' || persona.split('\n').indexOf('WHY YOU ARE') === -1) {
        throw new Error('[gen-plugin-agents] ' + PERSONA + ' is not the persona (no WHY YOU ARE line) — refusing to generate from it.');
    }
    const how = howLocal(r);
    const body = r.persona
        ? ['# THE PERSONA (' + PERSONA + ', verbatim — the system prompt the platform brain runs under)', '', persona.replace(/\s+$/, '')]
        : ['# NO PERSONA', '', 'On the platform this role asks with KB ' + r.knowledgebase_names.join(', ') + ', which carries no persona and no memories (measured: it answers as a generic assistant).',
            'So you, too, are not Maxi here: you are only the role your turn file names, and you judge only what it shows you.'];
    return [
        '---',
        'name: ' + agentName(id),
        'description: ' + JSON.stringify(r.description),
        'tools: ' + toolsFor(how).join(', '),
        '---',
        '<!-- GENERATED by scripts/gen-plugin-agents.mjs from site/app-assets/maxi-roles.js (ROLES.' + id + ')' +
            (r.persona ? ' and ' + PERSONA + ' (verbatim below)' : '; no persona: this role runs without it on the platform') +
            '. Do not edit: run node scripts/gen-plugin-agents.mjs --write. -->',
        '',
        how,
        ''
    ].concat(body, ['']).join('\n');
}

function cell(s) { return String(s).replace(/\|/g, '\\|').replace(/\n/g, ' '); }

/** The skill's roles table, from ROLES. */
export function renderRolesTable() {
    const rows = ROLE_ORDER.map(function (id) {
        const r = ROLES[id];
        return '| ' + [r.title, '`' + agentName(id) + '`', r.name + ', the ' + r.metaphor,
            r.knowledgebase_names.map(function (k) { return '`' + k + '`'; }).join(', '),
            r.persona ? 'yes' : 'no', r.localReads, HANDOFF_BY_ROLE[id]].map(cell).join(' | ') + ' |';
    });
    return [ROLES_MARKERS.begin, '',
        '| role | agent | is | asks with KB (platform) | persona | reads (local agent) | hands off |',
        '|---|---|---|---|---|---|---|'].concat(rows, ['',
        'The persona rides with KB `GodsWorld` only: a role asking without it (the Owl, on `General`) runs with no persona',
        'and no memories, on the platform and as a local agent alike.', '',
        'Every role is told the same world frame (`WORLD_FRAME`): the Designer and the Builder in the persona (its generated',
        'WORLD FRAME section), the Owl, who runs without the persona, in its first turn:', '',
        '> ' + WORLD_FRAME, '',
        'The Designer reads every message first. `' + READING_LINE + ' ' + DESIGNER_READINGS.outline + '` plans and builds as above. `' +
            READING_LINE + ' ' + DESIGNER_READINGS.question + '` ends at its answer:',
        'the report\'s `answer` holds the words and the memory files they named, `outcome` reads `answered in words …: no',
        'build, no Record`, and no Builder, Owl, Record or memory follows. On MiniMaxi an answer naming a file that is not',
        'under kb/GodsWorld stops the run by name. `' + READING_LINE + ' ' + DESIGNER_READINGS.both + '` answers first, then builds as an outline does.',
        '', ROLES_MARKERS.end]).join('\n');
}

function spliceRoles(text) {
    const b = text.indexOf(ROLES_MARKERS.begin);
    const e = text.indexOf(ROLES_MARKERS.end);
    if (b === -1 || e === -1 || e < b) { throw new Error('[gen-plugin-agents] ' + SKILL + ' carries no ROLES block — put the two marker lines where the roles table goes.'); }
    return text.slice(0, b) + renderRolesTable() + text.slice(e + ROLES_MARKERS.end.length);
}

/** Every generated file: the three agents and the skill with its roles table rendered. */
export function renderAll(root) {
    root = root || REPO;
    const persona = fs.readFileSync(path.join(root, PERSONA), 'utf8');
    return ROLE_ORDER.map(function (id) { return { id: id, path: agentPath(id), text: renderAgent(id, persona) }; })
        .concat([{ id: 'skill', path: SKILL, text: spliceRoles(fs.readFileSync(path.join(root, SKILL), 'utf8')) }]);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const mode = process.argv[2] || '';
    const files = renderAll(REPO);
    if (!mode) {
        files.forEach(function (f) { process.stdout.write('==> ' + f.path + '\n' + f.text); });
    } else if (mode === '--write') {
        fs.mkdirSync(path.join(REPO, AGENTS_DIR), { recursive: true });
        files.forEach(function (f) { fs.writeFileSync(path.join(REPO, f.path), f.text); });
        console.log('[gen-plugin-agents] wrote ' + files.map(function (f) { return f.path; }).join(', '));
    } else if (mode === '--check') {
        const stale = files.filter(function (f) {
            const p = path.join(REPO, f.path);
            return !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== f.text;
        });
        if (stale.length) {
            console.error('[gen-plugin-agents] STALE: ' + stale.map(function (f) { return f.path; }).join(', ') + ' — run: node scripts/gen-plugin-agents.mjs --write');
            process.exit(1);
        }
        console.log('[gen-plugin-agents] ' + files.length + ' files (agents + skill roles table) are current.');
    } else {
        console.error('usage: gen-plugin-agents.mjs [--write | --check]');
        process.exit(2);
    }
}
